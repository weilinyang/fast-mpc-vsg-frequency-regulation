function mdl=build_supplemental_network
here=fileparts(mfilename('fullpath'));root=fileparts(fileparts(here));
mdl='supplemental_network';target=fullfile(root,'code',[mdl '.slx']);
if bdIsLoaded(mdl),close_system(mdl,0);end
copyfile(fullfile(root,'code','fangzheng.slx'),target,'f');
load_system(target);
parent=[mdl '/VSG_1'];rotor=[parent '/转子机械方程'];
pos=get_param(rotor,'Position');ports=get_param(rotor,'PortHandles');
inputs=cell(1,3);outputs={};
for i=1:3
 lh=get_param(ports.Inport(i),'Line');
 if lh~=-1,inputs{i}=port_string(get_param(lh,'SrcPortHandle'),parent);end
end
lh=get_param(ports.Outport(1),'Line');
if lh~=-1
 ds=get_param(lh,'DstPortHandle');
 for i=1:numel(ds),outputs{end+1}=port_string(ds(i),parent);end %#ok<AGROW>
end
% Delete connected lines explicitly: delete_block can leave dangling lines
% attached to the old destinations.
for i=1:numel(ports.Inport)
 l=get_param(ports.Inport(i),'Line');if l~=-1,delete_line(l);end
end
l=get_param(ports.Outport(1),'Line');if l~=-1,delete_line(l);end
delete_block(rotor);
add_block('simulink/Ports & Subsystems/Subsystem',rotor,'Position',pos);
Simulink.SubSystem.deleteContents(rotor);
add_block('simulink/Sources/In1',[rotor '/Pref'],'Port','1','Position',[15 20 45 40]);
add_block('simulink/Sources/In1',[rotor '/Pe'],'Port','2','Position',[15 80 45 100]);
add_block('simulink/Sources/In1',[rotor '/theta0'],'Port','3','Position',[15 450 45 470]);
add_block('simulink/Sinks/Out1',[rotor '/theta'],'Port','1','Position',[800 440 830 460]);
add_block('simulink/User-Defined Functions/Level-2 MATLAB S-Function',...
 [rotor '/Revised MPC'],'FunctionName','supp_sfcn','Parameters','sup_cfg',...
 'Position',[160 90 320 170]);
add_block('simulink/Signal Routing/Demux',[rotor '/Controller outputs'],...
 'Outputs','4','Position',[340 90 345 230]);
add_block('simulink/Math Operations/Gain',[rotor '/Plant inertia multiplier'],...
 'Gain','sup_cfg.Jplant','Position',[375 135 475 155]);
add_block('simulink/Math Operations/Gain',[rotor '/Plant damping multiplier'],...
 'Gain','sup_cfg.Dplant','Position',[375 180 475 200]);
add_block('simulink/Math Operations/Sum',[rotor '/Power difference'],...
 'Inputs','+-','Position',[380 25 405 65]);
add_block('simulink/Math Operations/Product',[rotor '/Power to torque'],...
 'Inputs','*/','Position',[445 25 475 65]);
add_block('simulink/Math Operations/Product',[rotor '/Damping torque'],...
 'Inputs','**','Position',[495 180 525 220]);
add_block('simulink/Math Operations/Sum',[rotor '/Net torque'],...
 'Inputs','+-','Position',[545 40 565 80]);
add_block('simulink/Math Operations/Product',[rotor '/Acceleration'],...
 'Inputs','*/','Position',[595 40 625 80]);
add_block('simulink/Continuous/Integrator',[rotor '/Frequency error'],...
 'InitialCondition','0','Position',[650 40 680 80]);
add_block('simulink/Sources/Constant',[rotor '/Rated omega'],...
 'Value','sup_cfg.w0','Position',[650 110 710 135]);
add_block('simulink/Math Operations/Sum',[rotor '/Omega'],...
 'Inputs','++','Position',[745 55 770 95]);
add_block('simulink/Math Operations/Gain',[rotor '/Frequency Hz'],...
 'Gain','1/(2*pi)','Position',[790 90 865 120]);
add_block('simulink/Continuous/Integrator',[rotor '/Phase'],...
 'InitialCondition','0','Position',[640 400 670 440]);
add_block('simulink/Math Operations/Sum',[rotor '/Initial phase'],...
 'Inputs','++','Position',[730 430 760 470]);
add_block('simulink/Math Operations/Sum',[rotor '/MPC correction'],...
 'Inputs','+-','Position',[380 280 405 320]);
connections={'Pe/1','Revised MPC/2';'Omega/1','Revised MPC/1';...
 'Revised MPC/1','Controller outputs/1';...
 'Controller outputs/1','Power difference/1';'Pe/1','Power difference/2';...
 'Power difference/1','Power to torque/1';'Omega/1','Power to torque/2';...
 'Controller outputs/2','Plant inertia multiplier/1';...
 'Controller outputs/3','Plant damping multiplier/1';...
 'Plant damping multiplier/1','Damping torque/1';'Frequency error/1','Damping torque/2';...
 'Power to torque/1','Net torque/1';'Damping torque/1','Net torque/2';...
 'Net torque/1','Acceleration/1';'Plant inertia multiplier/1','Acceleration/2';...
 'Acceleration/1','Frequency error/1';'Frequency error/1','Omega/1';...
 'Rated omega/1','Omega/2';'Omega/1','Frequency Hz/1';...
 'Omega/1','Phase/1';'Phase/1','Initial phase/1';...
 'theta0/1','Initial phase/2';'Initial phase/1','theta/1';...
 'Controller outputs/1','MPC correction/1';'Pref/1','MPC correction/2'};
for i=1:size(connections,1),add_line(rotor,connections{i,1},connections{i,2},'autorouting','on');end
tags={'Pref_1','Pref/1';'P1','Pe/1';'f_1','Frequency Hz/1';'f1','Frequency Hz/1';...
 'w1','Omega/1';'Deltaw','Frequency error/1';'Pmpc','MPC correction/1';...
 'J','Controller outputs/2';'D','Controller outputs/3';'q','Controller outputs/4'};
for i=1:size(tags,1)
 name=['Goto ' tags{i,1}];
 add_block('simulink/Signal Routing/Goto',[rotor '/' name],...
 'GotoTag',tags{i,1},'TagVisibility','global',...
 'Position',[900 20+i*35 960 40+i*35]);
 add_line(rotor,tags{i,2},[name '/1'],'autorouting','on');
end
for i=1:3
 if ~isempty(inputs{i}),add_line(parent,inputs{i},['转子机械方程/' num2str(i)],'autorouting','on');end
end
for i=1:numel(outputs),add_line(parent,'转子机械方程/1',outputs{i},'autorouting','on');end
% Constant 15 kW reference for matched post-islanding comparisons.
pb=[parent '/Signal Builder'];pp=get_param(pb,'Position');
pph=get_param(pb,'PortHandles');ll=get_param(pph.Outport(1),'Line');
if ll~=-1,delete_line(ll);end
delete_block(pb);add_block('simulink/Sources/Constant',pb,'Value','sup_cfg.Pref','Position',pp);
add_line(parent,'Signal Builder/1','转子机械方程/1','autorouting','on');
% Preserve all switching devices and inner voltage/current control.
pg=[mdl '/波形观察/powergui'];
set_param(pg,'SimulationMode','Discrete','SampleTime','sup_cfg.electricalStep');
set_param(mdl,'SolverType','Fixed-step','Solver','ode3',...
 'FixedStep','sup_cfg.electricalStep','StopTime','sup_cfg.stop',...
 'SimulationMode','normal','SignalLogging','off','ReturnWorkspaceOutputs','on');
% Actual DC-source waveform; replace source while preserving its connections.
replace_block(mdl,'Name','DC Voltage Source',...
 'spsControlledVoltageSourceLib/Controlled Voltage Source','noprompt');
dc=[mdl '/DC Voltage Source'];
set_param(dc,'Initialize','on','Source_Type','DC','Amplitude','800',...
 'Phase','0','Frequency','0');
add_block('simulink/Sources/From Workspace',[mdl '/DC waveform'],...
 'VariableName','sup_dc','Interpolate','off',...
 'OutputAfterFinalValue','Holding final value','Position',[70 20 150 50]);
ph=get_param(dc,'PortHandles');input=get_param(ph.Inport(1),'Parent');
add_line(mdl,'DC waveform/1',[get_param(input,'Name') '/1'],'autorouting','on');
% Aggregate renewable power injected through three electrical current sources.
add_block('simulink/Signal Routing/From',[mdl '/Renewable bus voltage'],...
 'GotoTag','Vg','Position',[1000 20 1060 40]);
add_block('simulink/Discrete/Unit Delay',[mdl '/Renewable voltage delay'],...
 'SampleTime','sup_cfg.electricalStep','InitialCondition','[0;0;0]',...
 'Position',[1090 15 1120 45]);
add_block('simulink/Sources/Clock',[mdl '/Renewable clock'],'Position',[1090 90 1120 110]);
add_block('simulink/Sources/Constant',[mdl '/Renewable enable'],...
 'Value','double(sup_cfg.renewable)','Position',[1090 130 1150 150]);
f=[mdl '/Aggregate renewable injection'];
add_block('simulink/User-Defined Functions/MATLAB Function',f,...
 'Position',[1190 15 1370 145]);
rt=sfroot;chart=rt.find('-isa','Stateflow.EMChart','Path',f);
chart.Script=sprintf(['function [ia,ib,ic,P]=renewable(v,t,enabled)\n'...
 'P=0;\nif enabled>0.5 && t>=1\n'...
 'P=3000*(1+0.5*sin(2*pi*2*(t-1)));\nend\n'...
 'den=max(sum(v.^2),1e4);\ni=-P*v/den;\n'...
 'ia=i(1);ib=i(2);ic=i(3);\nend\n']);
add_line(mdl,'Renewable bus voltage/1','Renewable voltage delay/1','autorouting','on');
add_line(mdl,'Renewable voltage delay/1','Aggregate renewable injection/1','autorouting','on');
add_line(mdl,'Renewable clock/1','Aggregate renewable injection/2','autorouting','on');
add_line(mdl,'Renewable enable/1','Aggregate renewable injection/3','autorouting','on');
add_block('spsGroundLib/Ground',[mdl '/Renewable ground'],'Position',[1540 240 1560 260]);
bus=get_param([mdl '/pcc4'],'PortHandles');gr=get_param([mdl '/Renewable ground'],'PortHandles');
for i=1:3
 name=['Renewable current ' num2str(i)];
 add_block('spsControlledCurrentSourceLib/Controlled Current Source',[mdl '/' name],...
 'Position',[1450 15+i*60 1500 45+i*60]);
 set_param([mdl '/' name],'Initialize','on','Source_Type','DC','Amplitude','0',...
 'Phase','0','Frequency','0');
 p=get_param([mdl '/' name],'PortHandles');
 add_line(mdl,['Aggregate renewable injection/' num2str(i)],[name '/1'],'autorouting','on');
 add_line(mdl,bus.RConn(i),p.LConn(1),'autorouting','on');
 add_line(mdl,p.RConn(1),gr.LConn(1),'autorouting','on');
end
% Sample physical network signals at the common controller rate.
signals={'Vg','voltage';'Ig','gridCurrent';'Iabc_pcc_1','storageCurrent'};
for i=1:size(signals,1)
 a=['Log source ' signals{i,2}];b=['Log ' signals{i,2}];
 add_block('simulink/Signal Routing/From',[mdl '/' a],...
 'GotoTag',signals{i,1},'Position',[1750 30+i*80 1810 50+i*80]);
 add_block('simulink/Sinks/To Workspace',[mdl '/' b],...
 'VariableName',['sup_' signals{i,2}],'SaveFormat','Structure With Time',...
 'SampleTime','sup_cfg.Ts','MaxDataPoints','inf',...
 'Position',[1850 20+i*80 1950 60+i*80]);
 add_line(mdl,[a '/1'],[b '/1'],'autorouting','on');
end
save_system(mdl,target);
fprintf('SUPPLEMENTAL_MODEL_CREATED=%s\n',target);
end
function s=port_string(port,parent)
p=get_param(port,'Parent');n=get_param(p,'Name');idx=get_param(port,'PortNumber');
assert(strcmp(get_param(p,'Parent'),parent));
s=[n '/' num2str(idx)];
end
